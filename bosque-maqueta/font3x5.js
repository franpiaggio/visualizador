const ACC = { á: 'a', é: 'e', í: 'i', ó: 'o', ú: 'u', ñ: 'n', Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ñ: 'N' };
const cache = new Map();

// puntos encendidos de un carácter: [[col, fila], ...] con col 0..2 y fila 0..4
export function glyph(ch) {
  if (cache.has(ch)) return cache.get(ch);
  if (/[\u0300-\u036f]/.test(ch)) { cache.set(ch, []); return []; } // tilde combinada: no se planta
  const src = G[ch] ?? G[ACC[ch]] ?? (ch.trim() ? '### #.# #.# #.# ###' : null);
  const pts = [];
  if (src) src.split(' ').forEach((row, r) => [...row].forEach((c, k) => { if (c === '#') pts.push([k, r]); }));
  cache.set(ch, pts);
  return pts;
}
export const GLYPH_W = 4; // 3 puntos + 1 de separación
export const GLYPH_H = 7; // 5 puntos + 2 de interlineado
